/**
 * Generates docs/question-bank-reconciliation.md from the question bank, the
 * reconciliation records and the verbatim source inventory.
 *
 * Run with `npm run report:reconciliation` after changing any of the three.
 * The committed Markdown is a review artifact: regenerate it, do not hand-edit.
 */
import { writeFileSync } from "node:fs";
import { QUESTION_BANK } from "../src/features/interview/questionBank";
import {
  QUESTION_RECONCILIATION,
  SOURCE_GAPS,
  reconciliationSummary,
  type FlagKind,
  type GapDisposition,
  type ReconciliationVerdict,
} from "../src/features/interview/reconciliation";
import { SECTION_BY_ID } from "../src/features/interview/sections";
import { QUESTIONNAIRE_VERSION } from "../src/features/interview/types";
import { SOURCE_BY_ID, SOURCE_DOCUMENT, SOURCE_INVENTORY } from "../src/features/interview/sourceInventory";
import { validateQuestionBank, validateReconciliation } from "../src/features/interview/validateQuestionBank";

const summary = reconciliationSummary();
const bankIds = new Set(QUESTION_BANK.map((question) => question.id));

const VERDICT_LABEL: Record<ReconciliationVerdict, string> = {
  matches_source: "Matches source",
  split_source_compound: "Source compound split",
  wording_changed: "Wording changed",
  timeframe_changed: "Timeframe changed",
  timeframe_merged: "Timeframes merged",
  added_by_lpp: "Added by LPP",
  not_in_source: "Misattributed",
  held_for_review: "Held for review",
};

const FLAG_LABEL: Record<FlagKind, string> = {
  wording: "Wording",
  timeframe: "Timeframe",
  branching: "Branching",
  attribution: "Attribution",
  omission: "Omission",
};

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();
}

function truncate(value: string, max: number): string {
  const clean = escapeCell(value);
  return clean.length <= max ? clean : `${clean.slice(0, max - 1)}…`;
}

function windowsFor(questionId: string): string {
  const question = QUESTION_BANK.find((candidate) => candidate.id === questionId);
  const asked = question?.timeframe ?? (question?.compound ? "Component fields" : "No window stated");
  return asked;
}

const sections: string[] = [];

sections.push(`# Question bank ↔ source questionnaire reconciliation`);
sections.push("");
sections.push(
  `This document is generated by \`npm run report:reconciliation\` from \`src/features/interview/sourceInventory.ts\`, \`src/features/interview/reconciliation.ts\` and \`src/features/interview/questionBank.ts\`. Do not hand-edit it; change the data and regenerate.`,
);
sections.push("");
sections.push(`**Source document:** \`${SOURCE_DOCUMENT.path}\` (${SOURCE_DOCUMENT.pages} pages)`);
sections.push("");
sections.push(`**SHA-256:** \`${SOURCE_DOCUMENT.sha256}\``);
sections.push("");
sections.push(
  `**Plain-text extraction:** \`${SOURCE_DOCUMENT.textPath}\` — ${SOURCE_INVENTORY.length} source questions, one per bullet, ids \`SRC-001\` to \`SRC-${String(SOURCE_INVENTORY.length).padStart(3, "0")}\`.`,
);
sections.push("");
sections.push(`**Question bank version:** \`${QUESTIONNAIRE_VERSION}\` — ${QUESTION_BANK.length} rows.`);
sections.push("");
sections.push(
  `**Status:** reconciled, not signed off. ${QUESTION_BANK.filter((question) => question.sourceVerified).length} of ${QUESTION_BANK.length} rows carry \`sourceVerified: true\`. A named reviewer must accept each row and its action below before launch gate 1 is met.`,
);
sections.push("");

sections.push(`## Summary`);
sections.push("");
sections.push(`| Verdict | Rows |`);
sections.push(`| --- | --- |`);
for (const [verdict, count] of Object.entries(summary.byVerdict) as Array<[ReconciliationVerdict, number]>) {
  sections.push(`| ${VERDICT_LABEL[verdict]} | ${count} |`);
}
sections.push(`| **Total** | **${summary.rows}** |`);
sections.push("");
sections.push(`| Flag | Count |`);
sections.push(`| --- | --- |`);
for (const [kind, count] of Object.entries(summary.byFlag) as Array<[FlagKind, number]>) {
  sections.push(`| ${FLAG_LABEL[kind]} | ${count} |`);
}
sections.push(`| **Rows with at least one flag** | **${summary.rowsWithFlags}** |`);
sections.push("");
sections.push(
  `Source coverage: ${summary.sourceItems} source questions; ${summary.sourceItemsTraced} traced directly to a bank row; ${SOURCE_GAPS.length} recorded as gaps (${summary.gaps.merge_into} partially collected by an existing row, ${summary.gaps.out_of_scope} out of scope with a written reason, ${summary.gaps.add_question} still waiting on a new question). No source question is unacknowledged — \`npm run check:bank\` fails if one becomes so.`,
);
sections.push("");

sections.push(`## What this pass found`);
sections.push("");
sections.push(
  `The bank was built from the specification's coverage map rather than from the PDF. Nicotine, criminal history, medical history, alcohol and drug use, aviation and driving have since been rebuilt from the source, so ${summary.byVerdict.matches_source + summary.byVerdict.split_source_compound} of ${summary.rows} rows now follow their source wording, window and branching. The rest still differ, and the systemic findings are:`,
);
sections.push("");
sections.push(
  summary.byVerdict.timeframe_merged === 0
    ? `1. **Lookbacks are no longer flattened.** No row collapses two or more source windows into one answer. Nicotine, criminal history, medical history, alcohol and drug use, aviation and driving have each been split into one question per window (${summary.byVerdict.split_source_compound} split rows and ${summary.byVerdict.matches_source} rows that match the source).`
    : `1. **Lookbacks were flattened.** ${summary.byVerdict.timeframe_merged} rows still collapse two or more source windows into one answer — most often into "ever". Nicotine, criminal history, medical history, alcohol and drug use, aviation and driving have each been split into one question per window (${summary.byVerdict.split_source_compound} split rows and ${summary.byVerdict.matches_source} rows that match the source).`,
);
sections.push(
  `2. **Questions were narrowed or reframed.** ID-02 asks for city and country of birth where SRC-001 asks for state of birth; RES-02 replaces the source's "lived consistently in the USA" question with a different test; AVI-04 asks about the next 12 months where SRC-050 asks about two years. The nicotine cigar/pipe inversion, the drug-list reframing, the alcohol-infraction narrowing, the driving "charged" wording and the invented skin-cancer and traffic-violation exclusions found in earlier passes are all gone.`,
);
sections.push(
  `3. **Source questions were relabelled as LPP additions.** Eight rows carry source content under a "supplemental" label — SRC-033 to SRC-036 in MH-02; SRC-051 to SRC-054 in AVI-03; SRC-056 to SRC-058 in AVO-02; SRC-061 to SRC-066 in AVO-03 and AVO-04; SRC-055 in AVO-05; SRC-086 to SRC-089 in FIN-02; SRC-111 to SRC-113 in MIL-02. Supplemental is the correct label only for material the PDF does not contain.`,
);
sections.push(
  `4. **Two rows were not in the source at all.** ALC-01 (current drinking) and ID-03 (state of residence) were presented as source questions. Both are now marked supplemental; the underlying questions remain, flagged for a keep-or-remove decision.`,
);
sections.push(
  `5. **Every remaining gap has a recorded decision.** ${summary.gaps.add_question} source questions are still waiting on a new question. ${summary.gaps.out_of_scope} are recorded out of scope with a written reason — a blanket five-year check-up question, mental-health medication detail already collected by MED-09, mild or situational anxiety already inside MH-01, and avocation supporting detail such as track type, diving equipment and club membership. ${summary.gaps.merge_into} more are partly collected by an existing row.`,
);
sections.push(
  `6. **The crisis branch is closed.** MH-05, the current-crisis question, is now asked of every customer whatever they answer to MH-04, so a declined or uncertain answer no longer skips it and the support panel is never hidden behind a Yes. MH-06, detail about any attempt, is still held for clinical and legal review.`,
);
sections.push("");

sections.push(`## Row-by-row record`);
sections.push("");
sections.push(`| Row | Section | Verdict | Source items | Window asked | Flags |`);
sections.push(`| --- | --- | --- | --- | --- | --- |`);
for (const record of QUESTION_RECONCILIATION) {
  const section = SECTION_BY_ID.get(
    QUESTION_BANK.find((question) => question.id === record.questionId)?.section ?? "identity",
  );
  const sourceLabel = record.sourceIds.length > 0 ? record.sourceIds.join(", ") : "—";
  const flagLabel =
    record.flags.length > 0
      ? [...new Set(record.flags.map((flag) => FLAG_LABEL[flag.kind]))].join(", ")
      : "None";
  sections.push(
    `| \`${record.questionId}\` | ${escapeCell(section?.shortTitle ?? "")} | ${VERDICT_LABEL[record.verdict]} | ${sourceLabel} | ${escapeCell(windowsFor(record.questionId))} | ${flagLabel} |`,
  );
}
sections.push("");

sections.push(`## Decisions required`);
sections.push("");
for (const record of QUESTION_RECONCILIATION) {
  const question = QUESTION_BANK.find((candidate) => candidate.id === record.questionId);
  if (!question) continue;
  sections.push(`### ${record.questionId} — ${escapeCell(question.customerText)}`);
  sections.push("");
  sections.push(`- **Verdict:** ${VERDICT_LABEL[record.verdict]}`);
  sections.push(
    `- **Source:** ${
      record.sourceIds.length > 0
        ? record.sourceIds
            .map((id) => {
              const source = SOURCE_BY_ID[id];
              const window =
                !source || source.timeframe === "None stated" ? "no window" : source.timeframe;
              return `\`${id}\` (p.${source?.page ?? "?"}, ${window})`;
            })
            .join("; ")
        : "Not in the source questionnaire."
    }`,
  );
  if (record.sourceIds.length > 0) {
    const sourceText = record.sourceIds
      .map((id) => SOURCE_BY_ID[id]?.text)
      .filter(Boolean)
      .join(" ");
    sections.push(`- **Source wording:** ${truncate(sourceText, 600)}`);
  }
  sections.push(`- **Bank wording:** ${truncate(question.customerText, 300)}`);
  sections.push(`- **Window asked:** ${escapeCell(windowsFor(record.questionId))}`);
  sections.push(`- **Flags:**`);
  if (record.flags.length === 0) {
    sections.push(`  - None.`);
  } else {
    for (const flag of record.flags) {
      sections.push(`  - **${FLAG_LABEL[flag.kind]}:** ${escapeCell(flag.detail)}`);
    }
  }
  sections.push(`- **Decision:** ${escapeCell(record.action)}`);
  sections.push("");
}

sections.push(`## Source questions not fully represented`);
sections.push("");
sections.push(
  `Every source question is either traced to a bank row above or listed here. "Merge into" means an existing row collects part of it; "out of scope" means the review deliberately does not ask it, with the reason recorded; "add question" means nothing collects it and no decision has been recorded yet.`,
);
sections.push("");
sections.push(`| Source | Page | Window | Disposition | Target | Source wording | Why it is open |`);
sections.push(`| --- | --- | --- | --- | --- | --- | --- |`);
for (const gap of SOURCE_GAPS) {
  const source = SOURCE_BY_ID[gap.sourceId];
  const DISPOSITION_LABEL: Record<GapDisposition, string> = {
    merge_into: "Merge into",
    add_question: "Add question",
    out_of_scope: "Out of scope",
    hold: "Held",
  };
  const disposition = DISPOSITION_LABEL[gap.disposition];
  sections.push(
    `| \`${gap.sourceId}\` | ${source?.page ?? "?"} | ${escapeCell(source?.timeframe ?? "")} | ${disposition} | ${gap.target ? `\`${gap.target}\`` : "—"} | ${truncate(source?.text ?? "", 200)} | ${escapeCell(gap.reason)} |`,
  );
}
sections.push("");

sections.push(`## Sign-off`);
sections.push("");
sections.push(
  `For each row, the reviewer either accepts the bank wording, window and branch as an approved revision of the source, or changes them. On acceptance, set \`sourceVerified: true\` on the bank row and record the reviewer and date here. Do not set it for a row whose decision above is still open.`,
);
sections.push("");
sections.push(`| Reviewer | Date | Rows signed off | Notes |`);
sections.push(`| --- | --- | --- | --- |`);
sections.push(`| _(pending)_ | | 0 / ${QUESTION_BANK.length} | |`);
sections.push("");

const structural = validateQuestionBank();
const reconciliationIssues = validateReconciliation();

sections.push(`## Check output`);
sections.push("");
if (structural.length === 0 && reconciliationIssues.length === 0) {
  sections.push(
    `\`npm run check:bank\` passes: ${QUESTION_BANK.length} rows are structurally valid and every source question is acknowledged.`,
  );
} else {
  sections.push(`\`npm run check:bank\` reports issues:`);
  sections.push("");
  for (const issue of [...structural, ...reconciliationIssues]) sections.push(`- ${issue}`);
}
sections.push("");
sections.push(
  `Rows known to the bank but absent above: ${
    [...bankIds].filter((id) => !QUESTION_RECONCILIATION.some((record) => record.questionId === id)).join(", ") ||
    "none"
  }.`,
);
sections.push("");

writeFileSync("docs/question-bank-reconciliation.md", sections.join("\n"));
console.log(
  `Wrote docs/question-bank-reconciliation.md — ${QUESTION_BANK.length} rows, ${QUESTION_RECONCILIATION.length} records, ${SOURCE_GAPS.length} gaps.`,
);
if (structural.length > 0 || reconciliationIssues.length > 0) {
  console.error("The report was written, but the checks fail. See the Check output section.");
  process.exitCode = 1;
}
